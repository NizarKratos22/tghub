import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';
import { env } from '../../config/env';

/**
 * Where binary files live. The local-disk driver is for development and a
 * single server; an S3/R2 driver implements the same three calls when media
 * has to be shared between instances or served from a CDN.
 */
export interface ObjectStorage {
  put(key: string, body: Buffer): Promise<void>;
  open(key: string): Promise<{ stream: Readable; size: number } | null>;
  remove(key: string): Promise<void>;
}

/** Keys are generated by the API ("<objectId>-thumb.webp"); anything else is refused. */
const SAFE_KEY = /^[a-z0-9][a-z0-9._-]{0,127}$/i;

function assertKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes('..')) throw new Error(`Unsafe storage key: ${key}`);
}

class LocalDiskStorage implements ObjectStorage {
  private readonly root: string;
  private ready: Promise<unknown> | null = null;

  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private file(key: string) {
    assertKey(key);
    return path.join(this.root, key);
  }

  async put(key: string, body: Buffer): Promise<void> {
    this.ready ??= mkdir(this.root, { recursive: true });
    await this.ready;
    await writeFile(this.file(key), body);
  }

  async open(key: string) {
    const file = this.file(key);
    try {
      const info = await stat(file);
      return { stream: createReadStream(file), size: info.size };
    } catch {
      return null;
    }
  }

  async remove(key: string): Promise<void> {
    await rm(this.file(key), { force: true });
  }
}

export const storage: ObjectStorage = new LocalDiskStorage(env.MEDIA_DIR);
