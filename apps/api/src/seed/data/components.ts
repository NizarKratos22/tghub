import type { ComponentBrand, ComponentSegment } from '@tgh/shared';

/**
 * Relative performance index, roughly on a PassMark-like scale. Scores are
 * comparable within a type (CPU vs CPU, GPU vs GPU) and exist so requirement
 * tiers and rigs can be compared — they are not FPS predictions. Laptop GPU
 * scores assume a typical power limit; the same chip varies a lot between laptops.
 * Prices are intentionally absent: they are only filled from a dated local source.
 *
 * Keys are stable references (game requirement tiers use them) — never rename one.
 */
export interface ComponentSeed {
  key: string;
  brand: ComponentBrand;
  model: string;
  series: string;
  segment: ComponentSegment;
  score: number;
  vramGb: number | null;
  releaseYear: number | null;
  aliases: string[];
}

type CpuRow = [key: string, model: string, score: number, year: number, aliases?: string[]];
type GpuRow = [key: string, model: string, score: number, vramGb: number | null, year: number, aliases?: string[]];

const cpus = (brand: ComponentBrand, series: string, segment: ComponentSegment, rows: CpuRow[]): ComponentSeed[] =>
  rows.map(([key, model, score, year, aliases = []]) => ({ key, brand, model, series, segment, score, vramGb: null, releaseYear: year, aliases }));

const gpus = (brand: ComponentBrand, series: string, segment: ComponentSegment, rows: GpuRow[]): ComponentSeed[] =>
  rows.map(([key, model, score, vramGb, year, aliases = []]) => ({ key, brand, model, series, segment, score, vramGb, releaseYear: year, aliases }));

